import test from 'node:test';
import assert from 'node:assert/strict';
import { hash } from '../server/errors.mjs';
import { fixture, familiarTransfers } from './helpers.mjs';
import { greetingPrefix, sessionGreeting, bindGreeting } from '../src/chat/greetings.ts';

test('adaptive mock payment requires a bound browser, known payee and sufficient history', async t => {
  let history = [], signals = [];
  const f = await fixture(t, { puma: { policy: { flags: { risk_adaptive_auth: 'enabled', l0_single_password: 'enabled' } } },
    risk: { transactions: () => history, signals: () => signals } });
  const target = f.bank.get('SELECT number FROM payees WHERE id=?', f.recipient);
  const payeeRef = hash(target.number), source = f.services.accountFor(f.user).id;
  history = familiarTransfers(f.user.id, source, payeeRef);
  const login = 'bank_session=' + f.alice.token;
  const call = async (path, body, cookie = login, expected = 200) => {
    const res = await fetch(f.url + path, { method: body ? 'POST' : 'GET', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const data = await res.json();
    assert.equal(res.status, expected, JSON.stringify(data));
    return { data, cookie: res.headers.getSetCookie()[0]?.split(';')[0] };
  };
  const input = { sourceAccountRef: source, beneficiaryRef: f.recipient, amountMinor: 100, currency: 'CNY' };
  const base = '/v1/transfers/drafts';
  const draft = async cookie => (await call(base, input, cookie, 201)).data;
  const intent = async (d, cookie) => (await call(base + '/' + d.id + '/approval-intents', { version: d.version, payloadHash: d.payloadHash }, cookie)).data;
  const proof = (i, extra = {}) => ({ version: i.version, payloadHash: i.payloadHash, challengeId: i.challengeId, pin: '123456', ...extra });
  const first = await draft(login);
  assert.equal(first.risk.tier, 'L1');
  const bearerOnly = await f.call(base + '/' + first.id + '/approval-intents', { version: first.version, payloadHash: first.payloadHash });
  assert.equal(bearerOnly.data.error.code, 'PAYMENT_UI_REQUIRED');
  const i = await intent(first, login);
  assert.equal(i.smsOnly, true);
  await call(base + '/' + first.id + '/approve', proof(i), login, 403);
  const sms = (await call('/verify/start', { actionId: i.verificationActionId })).data;
  assert.equal(sms.faceChannel, 'not_required');
  const code = f.bank.get("SELECT body FROM notifications WHERE user_id=? AND title='模拟手机验证码' ORDER BY rowid DESC LIMIT 1", f.user.id).body.match(/验证码 (\d{6})/)[1];
  const { verificationToken } = (await call('/verify/complete', { id: sms.id, code })).data;
  const verified = await call(base + '/' + first.id + '/approve', proof(i, { verificationToken }));
  assert.equal(verified.data.status, 'SETTLED');
  const trusted = login + '; ' + verified.cookie;
  const next = await draft(trusted);
  assert.equal(next.risk.tier, 'L0', JSON.stringify(next.risk));
  const low = await intent(next, trusted);
  assert.equal(low.verificationActionId, null);
  const other = (await f.req('/auth/login', { phone: '13800138000', password: 'Bank123456' })).data;
  const otherCookie = 'bank_session=' + other.token + '; ' + verified.cookie;
  assert.equal((await call(base + '/' + next.id, undefined, otherCookie)).data.risk.tier, 'L1');
  await call(base + '/' + next.id + '/approve', proof(low), otherCookie, 403);
  assert.equal((await call(base + '/' + next.id + '/approve', proof(low), trusted)).data.status, 'SETTLED');
  const downgraded = await draft(trusted), bound = await intent(downgraded, trusted);
  const balance = f.balance().balance;
  const rejected = await call(base + '/' + downgraded.id + '/approve', proof(bound), login, 403);
  assert.equal(rejected.data.error.code, 'REAPPROVAL_REQUIRED');
  assert.equal(f.balance().balance, balance);
  history = [];
  assert.equal((await draft(trusted)).risk.tier, 'L1');
  history = familiarTransfers(f.user.id, source, payeeRef);
  const fact = { verified: true, sourceRef: 'backend', occurredAt: new Date().toISOString(), expiresAt: new Date(Date.now() + 60000).toISOString() };
  signals = [{ ...fact, type: 'NEW_DEVICE' }];
  assert.equal((await draft(trusted)).risk.tier, 'L1');
  signals = [{ ...fact, type: 'SAFE_ACCOUNT_SCAM' }];
  assert.equal((await draft(trusted)).risk.tier, 'L2');
  signals = [{ ...fact, type: 'CONFIRMED_FRAUD' }];
  const blocked = await draft(trusted);
  assert.equal(blocked.risk.tier, 'L3');
  await call(base + '/' + blocked.id + '/approval-intents', { version: blocked.version, payloadHash: blocked.payloadHash }, trusted, 409);
});

test('greeting uses local boundaries, DST, bounded safe variants and stable per-user session choices', t => {
  const prefixes = [[4,'你好'],[5,'早上好'],[10,'早上好'],[11,'中午好'],[13,'中午好'],[14,'下午好'],[17,'下午好'],[18,'晚上好'],[22,'晚上好'],[23,'你好']];
  for (const [hour, expected] of prefixes) assert.equal(greetingPrefix(new Date(Date.UTC(2026,0,1,hour,59)), 'UTC', false), expected);
  for (const zone of [undefined, 'invalid']) assert.equal(greetingPrefix(new Date(), zone, false), '你好');
  assert.equal(greetingPrefix(new Date('2026-03-07T10:00Z'), 'America/Chicago', false), '你好');
  assert.equal(greetingPrefix(new Date('2026-03-08T10:00Z'), 'America/Chicago', false), '早上好');
  const values = new Map();
  Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: k => values.get(k), setItem: (k,v) => values.set(k,v) } });
  t.after(() => delete globalThis.localStorage);
  const prefs = { english: false, concise: true, remember: true };
  const shown = Array.from({ length: 6 }, (_,i) => sessionGreeting('u', String(i), prefs));
  assert.equal(new Set(shown).size, 6);
  bindGreeting('u', '0', 'saved', true);
  assert.equal(sessionGreeting('u', 'saved', prefs), shown[0]);
  const english = sessionGreeting('another', 'saved', { english: true, concise: false, remember: true });
  assert.match(english, /^[A-Za-z ]+!/);
  for (const s of [...shown, english]) assert.ok(s.length && [...s].length <= 50);
});
