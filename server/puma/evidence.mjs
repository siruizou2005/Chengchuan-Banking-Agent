import { id, now } from '../db.mjs';
import { hash, requireThat } from '../errors.mjs';
const TYPE=/^(FINANCIAL_TRANSACTION|ACCOUNT_SECURITY_CHANGED|AGENT_TOOL_REQUESTED|AGENT_TOOL_COMPLETED|USER_INTENT_STATED|PROFILE_CORRECTED|TRANSFER_DRAFT_[A-Z_]+|APPROVAL_[A-Z_]+|RISK_FLAG_[A-Z_]+|DELEGATE_[A-Z_]+|PAYMENT_PROVIDER_[A-Z_]+)$/;
const ref=v=>typeof v==='string'&&/^[\w:./-]{1,200}$/.test(v);
export function createEvidenceStore(bank) {
  // This writer is an internal capability, never registered as an Agent tool or HTTP route.
  function ingest(event) {
    const e={event_id:id('PE'),ingested_at:now(),schema_version:1,payload_ref:null,...event};
    requireThat(ref(e.event_id)&&TYPE.test(e.type)&&bank.get('SELECT id FROM users WHERE id=?',e.user_id)&&
      ['agent','bank_api','trusted_ui','provider','risk_reviewer'].includes(e.source)&&['USER','AGENT','SYSTEM'].includes(e.initiated_by)&&
      e.schema_version===1&&ref(e.resource_ref)&&ref(e.correlation_id)&&['transfer','data_read','personalization','trait_research','security'].includes(e.consent_scope)&&
      ['SUFFICIENT','LIMITED','INCOMPLETE','UNRELIABLE'].includes(e.evidence_quality)&&
      Number.isFinite(Date.parse(e.occurred_at))&&Date.parse(e.occurred_at)<=Date.now()+60000&&
      (e.payload_ref===null||/^encrypted:[\w:/-]{1,180}$/.test(e.payload_ref)),'事件封套无效',400,'INVALID_EVIDENCE');
    e.occurred_at=new Date(e.occurred_at).toISOString();
    // Received time is generated by the backend, never accepted from the source.
    e.ingested_at=now();
    const fingerprint=hash(JSON.stringify([e.user_id,e.type,e.occurred_at,e.source,e.initiated_by,e.resource_ref,e.consent_scope,e.payload_ref,e.evidence_quality]));
    const previous=bank.get('SELECT * FROM puma_events WHERE event_id=? OR (user_id=? AND source=? AND type=? AND resource_ref=? AND fingerprint=?)',e.event_id,e.user_id,e.source,e.type,e.resource_ref,fingerprint);
    if(previous){requireThat(previous.fingerprint===fingerprint,'事件编号冲突',409,'EVIDENCE_CONFLICT');return {event_id:previous.event_id,status:'DUPLICATE'};}
    bank.run('INSERT INTO puma_events VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)',e.event_id,e.user_id,e.type,e.occurred_at,e.ingested_at,e.source,e.initiated_by,e.schema_version,e.correlation_id,e.resource_ref,e.consent_scope,e.payload_ref,e.evidence_quality,fingerprint);
    return {event_id:e.event_id,status:'INGESTED'};
  }
  function references(userId,ids) {
    requireThat(Array.isArray(ids)&&ids.length<=50,'证据引用无效',400,'INVALID_EVIDENCE');
    return ids.map(eventId=>{
      const e=bank.get('SELECT * FROM puma_events WHERE event_id=? AND user_id=?',eventId,userId);
      requireThat(e,'证据不存在或不属于当前用户',403,'EVIDENCE_FORBIDDEN');return e;
    });
  }
  return {ingest,references,list:user=>bank.all('SELECT event_id,type,occurred_at,ingested_at,source,resource_ref,evidence_quality FROM puma_events WHERE user_id=? ORDER BY ingested_at DESC LIMIT 100',user.id)};
}

// Audit adapter stores only opaque references and enumerated types, never chat or bank numbers.
export function mirrorAudit(db,user,action,resource,detail,at) {
  if(!user||!db.prepare('SELECT id FROM users WHERE id=?').get(user))return;
  const type=action.startsWith('risk.draft.')?'TRANSFER_DRAFT_'+action.split('.').at(-1).toUpperCase()
    :action.startsWith('risk.approval.')||action==='risk.user.approved'?'APPROVAL_'+action.split('.').at(-1).toUpperCase()
    :action.startsWith('risk.payment.')?'PAYMENT_PROVIDER_'+action.split('.').at(-1).toUpperCase()
    :action.startsWith('risk.review')||action.startsWith('risk.flag')?'RISK_FLAG_UPDATED'
    :action.startsWith('puma.delegate.')?'DELEGATE_'+action.split('.').at(-1).toUpperCase()
    :action==='policy.evaluated'&&detail.tool?'AGENT_TOOL_REQUESTED'
    :action==='authorization.executed'?'AGENT_TOOL_COMPLETED'
    :action==='transaction.completed'?'FINANCIAL_TRANSACTION'
    :action==='agent.injection'||action==='password.changed'||action==='pin.changed'?'ACCOUNT_SECURITY_CHANGED':null;
  if(!type)return;
  const resourceRef='ref:'+hash(String(resource||action)),fingerprint=hash(JSON.stringify([action,resource,detail,at]));
  db.prepare('INSERT OR IGNORE INTO puma_events VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run(id('PE'),user,type,at,at,action.startsWith('risk.payment.')?'provider':'agent','SYSTEM',1,resourceRef,resourceRef,'security',null,'SUFFICIENT',fingerprint);
  db.prepare('INSERT INTO puma_audit(user_id,action,resource_ref,detail,created_at) VALUES(?,?,?,?,?)').run(user,action,resourceRef,JSON.stringify({evidence_digest:fingerprint}),at);
}
